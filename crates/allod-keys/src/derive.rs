use std::fmt;

use bitcoin::bip32::{ChildNumber, DerivationPath, Xpriv};
use bitcoin::secp256k1::{Keypair, Secp256k1, SecretKey};
use bitcoin::NetworkKind;
use zeroize::Zeroizing;

use crate::{KeyError, RecoveryPhrase};

/// BIP32 purpose index for Allod' Nostr keys ("1237" as in NIP-06's coin type).
const PURPOSE: u32 = 1237;

/// A Nostr key pair. `Debug` shows only the public key.
#[derive(Clone)]
pub struct KeyPair {
    secret: SecretKey,
    /// x-only public key, lowercase hex (Nostr format).
    pub public_hex: String,
}

impl KeyPair {
    fn from_secret(secret: SecretKey) -> Self {
        let secp = Secp256k1::signing_only();
        let (xonly, _) = Keypair::from_secret_key(&secp, &secret).x_only_public_key();
        KeyPair { secret, public_hex: xonly.to_string() }
    }

    /// A new random key pair (connection client keys generated by Allod, SPEC §8.6).
    pub fn random() -> Self {
        loop {
            let bytes: Zeroizing<[u8; 32]> = Zeroizing::new(rand::random());
            if let Ok(secret) = SecretKey::from_slice(&bytes[..]) {
                return KeyPair::from_secret(secret);
            }
        }
    }

    /// The 32-byte secret key as lowercase hex. Handle with care.
    pub fn expose_secret_hex(&self) -> Zeroizing<String> {
        Zeroizing::new(hex::encode(self.secret.secret_bytes()))
    }

    /// The 32-byte secret key.
    pub fn expose_secret_bytes(&self) -> Zeroizing<[u8; 32]> {
        Zeroizing::new(self.secret.secret_bytes())
    }
}

impl fmt::Debug for KeyPair {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "KeyPair({})", self.public_hex)
    }
}

/// Deterministic Nostr keys derived from the recovery phrase (SPEC §4.2):
///
/// | Use | Path |
/// |---|---|
/// | Legacy shared wallet service key | `m/1237'/0'/0'` |
/// | Per-connection wallet key | `m/1237'/1'/{app_id}'` |
/// | Zap receipts (LNURL, SPEC §12) | `m/1237'/2'/0'` |
/// | Backup encryption (SPEC §2.3.7) | `m/1237'/3'/0'` |
///
/// These paths do not overlap with the ones LDK derives from the same seed.
pub struct NostrKeys {
    master: Xpriv,
}

impl NostrKeys {
    /// Builds the BIP32 master key from the phrase's seed.
    pub fn from_phrase(phrase: &RecoveryPhrase) -> Result<Self, KeyError> {
        let seed = phrase.seed();
        let master = Xpriv::new_master(NetworkKind::Main, &seed[..])
            .map_err(|e| KeyError::Derivation(e.to_string()))?;
        Ok(NostrKeys { master })
    }

    fn derive(&self, branch: u32, index: u32) -> Result<KeyPair, KeyError> {
        let path =
            DerivationPath::from(vec![hardened(PURPOSE)?, hardened(branch)?, hardened(index)?]);
        let secp = Secp256k1::signing_only();
        let child = self
            .master
            .derive_priv(&secp, &path)
            .map_err(|e| KeyError::Derivation(e.to_string()))?;
        Ok(KeyPair::from_secret(child.private_key))
    }

    /// Legacy shared wallet service key (`m/1237'/0'/0'`).
    pub fn service_key(&self) -> Result<KeyPair, KeyError> {
        self.derive(0, 0)
    }

    /// Wallet key for one NWC connection (`m/1237'/1'/{app_id}'`).
    pub fn app_wallet_key(&self, app_id: u64) -> Result<KeyPair, KeyError> {
        let index = u32::try_from(app_id)
            .ok()
            .filter(|i| *i < (1 << 31))
            .ok_or(KeyError::AppIdOutOfRange(app_id))?;
        self.derive(1, index)
    }

    /// Key that signs NIP-57 zap receipts (`m/1237'/2'/0'`).
    pub fn zap_key(&self) -> Result<KeyPair, KeyError> {
        self.derive(2, 0)
    }

    /// Key for client-side backup encryption (`m/1237'/3'/0'`).
    pub fn backup_key(&self) -> Result<KeyPair, KeyError> {
        self.derive(3, 0)
    }
}

impl fmt::Debug for NostrKeys {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("NostrKeys(redacted)")
    }
}

fn hardened(index: u32) -> Result<ChildNumber, KeyError> {
    ChildNumber::from_hardened_idx(index).map_err(|e| KeyError::Derivation(e.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn keys() -> NostrKeys {
        let phrase = RecoveryPhrase::parse(
            "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon \
             abandon about",
        )
        .unwrap();
        NostrKeys::from_phrase(&phrase).unwrap()
    }

    #[test]
    fn derivation_is_deterministic_and_distinct() {
        let a = keys();
        let b = keys();
        assert_eq!(
            a.app_wallet_key(1).unwrap().public_hex,
            b.app_wallet_key(1).unwrap().public_hex
        );
        let all = [
            a.service_key().unwrap().public_hex,
            a.app_wallet_key(0).unwrap().public_hex,
            a.app_wallet_key(1).unwrap().public_hex,
            a.zap_key().unwrap().public_hex,
            a.backup_key().unwrap().public_hex,
        ];
        let mut unique = all.to_vec();
        unique.sort();
        unique.dedup();
        assert_eq!(unique.len(), all.len());
        assert!(all.iter().all(|k| k.len() == 64));
    }

    #[test]
    fn known_path_matches_manual_bip32() {
        // Cross-check the helper against an explicit path string.
        let phrase = RecoveryPhrase::parse(
            "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon \
             abandon about",
        )
        .unwrap();
        let secp = Secp256k1::new();
        let master = Xpriv::new_master(NetworkKind::Main, &phrase.seed()[..]).unwrap();
        let path: DerivationPath = "m/1237'/1'/42'".parse().unwrap();
        let expected = KeyPair::from_secret(master.derive_priv(&secp, &path).unwrap().private_key);
        assert_eq!(keys().app_wallet_key(42).unwrap().public_hex, expected.public_hex);
    }

    #[test]
    fn rejects_out_of_range_app_ids() {
        assert!(keys().app_wallet_key(1 << 31).is_err());
        assert!(keys().app_wallet_key((1 << 31) - 1).is_ok());
    }

    #[test]
    fn debug_does_not_leak_secrets() {
        let k = keys().zap_key().unwrap();
        let shown = format!("{k:?}");
        assert!(shown.contains(&k.public_hex));
        assert!(!shown.contains(k.expose_secret_hex().as_str()));
        assert_eq!(format!("{:?}", keys()), "NostrKeys(redacted)");
    }
}
