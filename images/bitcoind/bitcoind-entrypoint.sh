#!/usr/bin/env bash
# Writes bitcoin.conf from environment variables and starts bitcoind.
# Pruning rules: SPEC §2.3.2 (minimum 5000 MiB unless 0 = unpruned; regtest exempt).
set -euo pipefail
log() { echo "[bitcoind-entrypoint] $*" >&2; }
die() { log "error: $*"; exit 1; }

DATA=/data
NETWORK=${BITCOIN_NETWORK:-bitcoin}
case "$NETWORK" in
  bitcoin) chain=main ;;
  signet|testnet4|regtest) chain=$NETWORK ;;
  testnet) chain="test" ;;
  *) die "unknown BITCOIN_NETWORK $NETWORK" ;;
esac

PRUNE=${BITCOIN_PRUNE:-50000}
[[ "$PRUNE" =~ ^[0-9]+$ ]] || die "BITCOIN_PRUNE must be a number of MiB"
if [ "$chain" != regtest ] && [ "$PRUNE" != 0 ] && [ "$PRUNE" -lt 5000 ]; then
  die "BITCOIN_PRUNE=$PRUNE is below the 5000 MiB minimum (about 2 weeks of blocks). Use 0 for an unpruned node."
fi

rpcauth() { # user password -> rpcauth line
  local salt hash
  salt=$(openssl rand -hex 16)
  hash=$(printf '%s' "$2" | openssl dgst -sha256 -hmac "$salt" | awk '{print $NF}')
  echo "rpcauth=$1:$salt\$$hash"
}

# shellcheck source=sync-tuning.sh
source /usr/local/bin/sync-tuning.sh
DB_CACHE_REQUESTED=${BITCOIN_DBCACHE:-450}
[[ "$DB_CACHE_REQUESTED" =~ ^[0-9]+$ ]] || die "BITCOIN_DBCACHE must be a number of MiB"
DB_CACHE=$(steady_dbcache "$DB_CACHE_REQUESTED")
SYNC_PROFILE=$(sync_profile "$chain" "${BITCOIN_EXTRA_CONF:-}")

: "${BITCOIN_RPC_USER:?BITCOIN_RPC_USER is required}"
: "${BITCOIN_RPC_PASS:?BITCOIN_RPC_PASS is required}"

{
  echo "# Generated by bitcoind-entrypoint.sh on every start. Edit the environment instead."
  echo "chain=$chain"
  echo "server=1"
  echo "disablewallet=${BITCOIN_DISABLE_WALLET:-1}"
  echo "prune=$PRUNE"
  if [ -n "$SYNC_PROFILE" ]; then
    echo "# Initial sync profile for this machine; replaced after the sync (sync-tuning.sh)."
    printf '%s\n' "$SYNC_PROFILE"
    printf '%s\n' "$SYNC_PROFILE" | grep -q '^dbcache=' || echo "dbcache=$DB_CACHE"
  else
    echo "dbcache=$DB_CACHE"
  fi
  echo "blockfilterindex=${BITCOIN_BLOCKFILTERINDEX:-1}"
  echo "txindex=${BITCOIN_TXINDEX:-0}"
  echo "printtoconsole=1"
  echo "[$chain]"
  echo "rpcbind=0.0.0.0"
  echo "rpcallowip=127.0.0.1"
  echo "rpcallowip=10.0.0.0/8"
  echo "rpcallowip=172.16.0.0/12"
  echo "rpcallowip=192.168.0.0/16"
  [ -n "${BITCOIN_RPC_PORT:-}" ] && echo "rpcport=$BITCOIN_RPC_PORT"
  [ "${BITCOIN_REST:-0}" = 1 ] && echo "rest=1"
  rpcauth "$BITCOIN_RPC_USER" "$BITCOIN_RPC_PASS"
  if [ -n "${BITCOIN_RO_RPC_USER:-}" ]; then
    # Read-only user for Allod sync progress (SPEC §2.3.4).
    rpcauth "$BITCOIN_RO_RPC_USER" "${BITCOIN_RO_RPC_PASS:?BITCOIN_RO_RPC_PASS is required}"
    echo "rpcwhitelist=$BITCOIN_RO_RPC_USER:getblockchaininfo,getnetworkinfo,estimatesmartfee"
    echo "rpcwhitelistdefault=0"
  fi
  if [ "$chain" = regtest ]; then
    echo "fallbackfee=0.0002"
    echo "listen=1"
    echo "bind=0.0.0.0"
  fi
  [ -n "${BITCOIN_EXTRA_CONF:-}" ] && printf '%s\n' "$BITCOIN_EXTRA_CONF"
} >"$DATA/bitcoin.conf"
chmod 0600 "$DATA/bitcoin.conf"

log "chain=$chain prune=$PRUNE"
if [ -n "$SYNC_PROFILE" ]; then
  log "initial sync profile ($(mem_mib) MiB headroom, $(nproc) CPUs): $(printf '%s' "$SYNC_PROFILE" | tr '\n' ' ')"
  /usr/local/bin/sync-tuning.sh watch &
fi
# Optional fast sync helper (AssumeUTXO), only when Allod shares a control directory.
if [ -d /control ] && [ -w /control ]; then
  /usr/local/bin/assumeutxo.sh &
fi
exec bitcoind -conf="$DATA/bitcoin.conf" -datadir="$DATA"
